"""
libreldr_entries.py

Single source of truth for UEFI-only libreldr boot entries.
This generates the libreldr.conf file read by libreldr.efi.

Note: libreldr.c's parser understands `title`, `linux`, `chain`, `options`,
`timeout`, `default`, and `quiet`. It has no `initrd` directive — the initramfs is
passed to the Linux EFI stub via `initrd=` inside the kernel command line,
which is forwarded as LoadOptions when libreldr hands off via StartImage().
FreeBSD entries should use `chain` to hand off to loader.efi.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Entry:
    title: str
    options: str  # kernel command line


# UEFI paths are relative to the root of the ESP.
# We use backslashes here to be explicitly UEFI-compliant.
KERNEL_PATH = r"\EFI\yetios\vmlinuz.efi"
INITRD_PATH = r"\EFI\yetios\initramfs.img"

# Common initrd= argument appended to every entry's command line so the
# Linux EFI stub locates the initramfs on the ESP at hand-off.
_INITRD_ARG = f"initrd={INITRD_PATH}"

# Cmdline tokens that complement the snowcone boot splash. These are the
# committed defaults for legacy Linux EFI-stub entries.
#
#   - quiet                       silences most kernel printk output
#   - loglevel=0                  suppress ALL console kernel messages
#                                 (anything that leaks through 'quiet')
#   - vt.global_cursor_default=0  hides the text-mode cursor
#   - udev.log_level=3            silences udev messages
#   - rd.udev.log_level=3         same, but for the initramfs udev
#   - fbcon=nodefer               don't print the fbcon banner
#   - console=tty12               route kernel console output to tty12
#                                 so anything that DOES print can't
#                                 land on the splash (tty1)
#
# Only applied to entries that should boot silently. Debug/Log/RAM/Emergency
# modes keep verbose kernel output so you can actually see what's happening.
_SPLASH_ARGS = "quiet loglevel=0 vt.global_cursor_default=0 udev.log_level=3 rd.udev.log_level=3 fbcon=nodefer console=tty12"

# Verbose cmdline for diagnostic entries. The opposite of _SPLASH_ARGS:
# put kernel messages back on tty1, crank loglevel up so we actually
# see what went wrong, and don't redirect console anywhere.
_DEBUG_ARGS = "loglevel=7 console=tty1"

# Defined entries for the boot menu
ENTRIES = [
    Entry("YetiOS",
          f"root=LABEL=yetios-root ro {_SPLASH_ARGS}"),
    Entry("YetiOS (Debug)",
          f"root=LABEL=yetios-root rw debug {_DEBUG_ARGS}"),
    Entry("YetiOS (Log file)",
          "root=LABEL=yetios-root ro console=ttyS0,115200 loglevel=7"),
    Entry("YetiOS (RAM Disk)",
          f"root=/dev/ram0 init=/sbin/init {_DEBUG_ARGS}"),
    Entry("YetiOS (Emergency Management Services)",
          f"root=LABEL=yetios-root ro single {_DEBUG_ARGS}"),
]

TIMEOUT_SECONDS = 5
DEFAULT_INDEX   = 0


def render_libreldr_conf() -> str:
    """
    Generates the config file consumed by libreldr.efi.
    Located at: /EFI/libreldr/libreldr.conf on the ESP.
    """
    lines = [
        "# libreldr -- UEFI boot configuration",
        "# Generated by libreldr_entries.py. UEFI-only mode.",
        "",
        f"timeout {TIMEOUT_SECONDS}",
        f"default {DEFAULT_INDEX}",
        "",
    ]
    for e in ENTRIES:
        # Always prepend the initrd= argument; the Linux EFI stub reads it
        # from its LoadOptions and pulls the initramfs from the ESP.
        full_options = f"{_INITRD_ARG} {e.options}"
        lines += [
            f"title {e.title}",
            f"linux {KERNEL_PATH}",
            f"options {full_options}",
            "",
        ]
    return "\n".join(lines)


def render_freebsd_chain_conf(loader_path: str = r"\EFI\freebsd\loader.efi") -> str:
    """
    Generates a minimal FreeBSD chainload config for YetiOS.
    Located at: /EFI/libreldr/libreldr.conf on the ESP.
    """
    return "\n".join([
        "# libreldr -- FreeBSD chainload configuration",
        "# Generated by libreldr_entries.py. UEFI-only mode.",
        "",
        "timeout 5",
        "default 0",
        "quiet yes",
        "",
        "title YetiOS",
        f"chain {loader_path}",
        "",
    ])
