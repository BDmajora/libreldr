"""
libreldr_entries.py

Single source of truth for libreldr boot entries.

Both backends now read the SAME config file (libreldr.conf):
  - UEFI: libreldr.efi reads /EFI/libreldr/libreldr.conf
  - BIOS: libreldr.c32 reads /libreldr.conf (loaded by tiny syslinux.cfg)

The tiny syslinux.cfg just chainloads libreldr.c32 — all menu rendering
is done by our own code, not menu.c32.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Entry:
    title: str
    options: str  # kernel command line


ENTRIES = [
    Entry("YetiOS",                                   "root=LABEL=yetios-root ro quiet"),
    Entry("YetiOS (Debug)",                           "root=LABEL=yetios-root rw debug"),
    Entry("YetiOS (Log file)",                        "root=LABEL=yetios-root ro console=ttyS0,115200"),
    Entry("YetiOS (RAM Disk)",                        "root=/dev/ram0 init=/sbin/init"),
    Entry("YetiOS (Emergency Management Services)",   "root=LABEL=yetios-root ro single"),
]

TIMEOUT_SECONDS = 5
DEFAULT_INDEX = 0
INITRD = "initramfs.img"


def render_libreldr_conf() -> str:
    """Shared config file consumed by both libreldr.efi and libreldr.c32.

    UEFI uses backslash paths inside the ESP; BIOS sees forward-slash
    paths on the same FAT volume. We emit forward slashes — both readers
    normalize internally.
    """
    lines = [
        "# libreldr -- boot configuration (shared BIOS+UEFI)",
        "# Generated by yeti-build. Do not edit by hand.",
        "",
        f"timeout {TIMEOUT_SECONDS}",
        f"default {DEFAULT_INDEX}",
        "",
    ]
    for e in ENTRIES:
        lines += [
            f"title {e.title}",
            # UEFI: libreldr.efi rewrites this to \EFI\yetios\vmlinuz.efi
            #       internally via NormalizePath(). BIOS: libreldr.c32 reads
            #       /vmlinuz from the FAT root directly.
            "linux /vmlinuz",
            f"initrd /{INITRD}",
            f"options {e.options}",
            "",
        ]
    return "\n".join(lines)


def render_syslinux_cfg() -> str:
    """Tiny syslinux.cfg that just hands off to libreldr.c32.

    All UI is in libreldr.c32; syslinux just loads us and gets out
    of the way.
    """
    return (
        "# Generated by yeti-build. syslinux just chainloads libreldr.c32;\n"
        "# all UI is drawn by libreldr itself.\n"
        "DEFAULT libreldr\n"
        "PROMPT 0\n"
        "TIMEOUT 0\n"
        "\n"
        "LABEL libreldr\n"
        "    COM32 libreldr.c32\n"
    )