"""
integration/libreldr_entries.py

Single source of truth for libreldr boot entries. Stage 7 imports this
and generates both backend configs from it:

  - libreldr.conf  (UEFI side, read by libreldr.efi)
  - syslinux.cfg   (BIOS side, read by syslinux)

Edit boot entries here. The wording matches the ReactOS screenshot.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Entry:
    title: str          # Menu display string
    kernel: str         # Path on /boot — same partition for BIOS and ESP for UEFI
    options: str        # Kernel command line


# The default entry is the first in this list (index 0).
ENTRIES = [
    Entry(
        title="YetiOS",
        kernel="vmlinuz",
        options="root=LABEL=yetios-root ro quiet",
    ),
    Entry(
        title="YetiOS (Debug)",
        kernel="vmlinuz",
        options="root=LABEL=yetios-root rw debug",
    ),
    Entry(
        title="YetiOS (Log file)",
        kernel="vmlinuz",
        options="root=LABEL=yetios-root ro console=ttyS0,115200",
    ),
    Entry(
        title="YetiOS (RAM Disk)",
        kernel="vmlinuz",
        options="root=/dev/ram0 init=/sbin/init",
    ),
    Entry(
        title="YetiOS (Emergency Management Services)",
        kernel="vmlinuz",
        options="root=LABEL=yetios-root ro single",
    ),
]

TIMEOUT_SECONDS = 5
DEFAULT_INDEX = 0
INITRD = "initramfs.img"


# ---------------------------------------------------------------------------
# UEFI: libreldr.conf
# ---------------------------------------------------------------------------

def render_libreldr_conf() -> str:
    """UEFI config consumed by libreldr.efi. Paths use ESP-relative backslashes."""
    lines = [
        "# libreldr — UEFI configuration",
        "# Generated by yeti-build. Do not edit by hand.",
        "",
        f"timeout {TIMEOUT_SECONDS}",
        f"default {DEFAULT_INDEX}",
        "",
    ]
    for e in ENTRIES:
        lines += [
            f"title {e.title}",
            f"linux \\EFI\\yetios\\vmlinuz.efi",
            f"options {e.options}",
            "",
        ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# BIOS: syslinux.cfg, themed to mirror FreeLdr MinimalUI
# ---------------------------------------------------------------------------

def render_syslinux_cfg() -> str:
    """
    BIOS config consumed by syslinux (menu.c32). The MENU statements
    theme it to mirror the FreeLdr MinimalUI:
      - Black background, light-gray text.
      - Inverse-video selection bar (black-on-lightgray).
      - Same header text, same help lines, same countdown line.

    Syslinux's `prompt 1` shows the boot prompt; `menu.c32` is the
    text-menu module. Timeout is in deciseconds, hence x10.
    """
    lines = [
        "# libreldr — BIOS configuration",
        "# Generated by yeti-build. Do not edit by hand.",
        "",
        "UI menu.c32",
        f"DEFAULT {ENTRIES[DEFAULT_INDEX].title}",
        f"TIMEOUT {TIMEOUT_SECONDS * 10}",
        "PROMPT 0",
        "",
        "# Theme: FreeLdr MinimalUI lookalike",
        'MENU TITLE Please select the operating system to start:',
        "MENU CLEAR",
        "MENU ROWS " + str(len(ENTRIES)),
        "MENU TABMSGROW " + str(len(ENTRIES) + 5),
        "MENU TIMEOUTROW " + str(len(ENTRIES) + 7),
        "MENU HELPMSGROW " + str(len(ENTRIES) + 10),
        "",
        "# Colors:  ATTR  FG/BG (intensity prefix optional)",
        "MENU COLOR screen       37;40    #FFAAAAAA #00000000 none",
        "MENU COLOR border       30;40    #00000000 #00000000 none",
        "MENU COLOR title        37;40    #FFAAAAAA #00000000 none",
        "MENU COLOR unsel        37;40    #FFAAAAAA #00000000 none",
        "MENU COLOR sel          30;47    #FF000000 #FFAAAAAA none",
        "MENU COLOR hotkey       37;40    #FFAAAAAA #00000000 none",
        "MENU COLOR hotsel       30;47    #FF000000 #FFAAAAAA none",
        "MENU COLOR timeout_msg  37;40    #FFAAAAAA #00000000 none",
        "MENU COLOR timeout      37;40    #FFAAAAAA #00000000 none",
        "MENU COLOR help         37;40    #FFAAAAAA #00000000 none",
        "MENU COLOR tabmsg       37;40    #FFAAAAAA #00000000 none",
        "",
        "MENU TABMSG Use ^ and v to move the highlight to your choice. Press ENTER to choose.",
        "MENU TIMEOUTMSG Seconds until highlighted choice will be started automatically: #",
        "",
        "MENU HSHIFT 0",
        "MENU VSHIFT 1",
        "MENU WIDTH 78",
        "MENU MARGIN 0",
        "",
    ]
    for e in ENTRIES:
        lines += [
            f"LABEL {e.title}",
            f"    MENU LABEL {e.title}",
            f"    KERNEL /{e.kernel}",
            f"    INITRD /{INITRD}",
            f"    APPEND {e.options}",
            "",
        ]

    # The F8 hint line goes in the help area at the bottom.
    lines += [
        "MENU SEPARATOR",
        "TEXT HELP",
        "For troubleshooting and advanced startup options for YetiOS, press F8.",
        "ENDTEXT",
    ]
    return "\n".join(lines)