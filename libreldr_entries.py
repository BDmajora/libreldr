"""
libreldr_entries.py

Single source of truth for UEFI-only libreldr boot entries.
This generates the libreldr.conf file read by libreldr.efi.
"""

from dataclasses import dataclass

@dataclass(frozen=True)
class Entry:
    title: str
    options: str  # kernel command line

# Defined entries for the boot menu
ENTRIES = [
    Entry("YetiOS",                                   "root=LABEL=yetios-root ro quiet"),
    Entry("YetiOS (Debug)",                           "root=LABEL=yetios-root rw debug"),
    Entry("YetiOS (Log file)",                        "root=LABEL=yetios-root ro console=ttyS0,115200"),
    Entry("YetiOS (RAM Disk)",                        "root=/dev/ram0 init=/sbin/init"),
    Entry("YetiOS (Emergency Management Services)",   "root=LABEL=yetios-root ro single"),
]

TIMEOUT_SECONDS = 5
DEFAULT_INDEX = 0

# UEFI paths are relative to the root of the ESP.
# We use backslashes here to be explicitly UEFI-compliant.
KERNEL_PATH = r"\EFI\yetios\vmlinuz.efi"
INITRD_PATH = r"\EFI\yetios\initramfs.img"

def render_libreldr_conf() -> str:
    """
    Generates the config file consumed by libreldr.efi.
    Located at: /EFI/libreldr/libreldr.conf on the ESP.
    """
    lines = [
        "# libreldr -- UEFI boot configuration",
        "# Generated by yeti-build. UEFI-only mode.",
        "",
        f"timeout {TIMEOUT_SECONDS}",
        f"default {DEFAULT_INDEX}",
        "",
    ]
    
    for e in ENTRIES:
        lines += [
            f"title {e.title}",
            f"linux {KERNEL_PATH}",
            f"initrd {INITRD_PATH}",
            f"options {e.options}",
            "",
        ]
    
    return "\n".join(lines)